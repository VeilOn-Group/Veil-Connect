export type Key = keyof (typeof dict)["ru"];

export const LangContext = createContext<Lang>("ru");

export function useT(): (k: Key) => string {
  const lang = useContext(LangContext);
  return (k) => dict[lang][k] ?? dict.en[k];
}

export function detectLang(): Lang {
  const l = navigator.language.toLowerCase();
  if (l.startsWith("sr") || l.startsWith("hr") || l.startsWith("bs")) return "sr";
  if (l.startsWith("ru") || l.startsWith("uk") || l.startsWith("be")) return "ru";
  return "en";
}
